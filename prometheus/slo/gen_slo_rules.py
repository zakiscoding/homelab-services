"""Generates prometheus/config/rules/slo.yml from the SLO table below.

Each SLO is an error ratio (bad events / all events, or the failed fraction of a synthetic probe)
and a target. For each one this writes:

* recording rules  slo:sli_error:ratio_rate<window>{slo="..."}  for every window the alerts use;
* multiwindow, multi-burn-rate alerts (Google SRE Workbook, ch. 5): an alert fires only when both
  the long and the short window burn the error budget faster than the factor, so it pages fast on
  a real outage and stops soon after recovery:
      page    burn 14.4x over 1h and 5m   (2% of a 30-day budget in an hour)
      page    burn  6x   over 6h and 30m  (5% in 6 hours)
      ticket  burn  1x   over 3d and 6h   (on track to spend the whole budget)

Run from the repo root:  python prometheus/slo/gen_slo_rules.py   (tests/check it is up to date)
"""

from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "config" / "rules" / "slo.yml"

WINDOWS = ["5m", "30m", "1h", "6h", "3d"]
BURN_ALERTS = [  # (severity, long, short, factor)
    ("page", "1h", "5m", 14.4),
    ("page", "6h", "30m", 6),
    ("ticket", "3d", "6h", 1),
]

GATEWAY = 'service_name="vllm-gateway",span_kind="SPAN_KIND_SERVER"'
CHAT = 'job="homelab-api",endpoint="/chat"'

SLOS = [
    {
        "slo": "chat-api-availability",
        "target": 0.99,
        "summary": "Homelab API /chat answers without a 5xx",
        "error": f'sum(rate(homelab_http_requests_total{{{CHAT},status=~"5.."}}[{{w}}]))',
        "total": f"sum(rate(homelab_http_requests_total{{{CHAT}}}[{{w}}]))",
    },
    {
        "slo": "chat-api-latency",
        "target": 0.95,
        "summary": "Homelab API /chat answers within 15 s",
        "error": (f'sum(rate(homelab_http_request_duration_seconds_count{{{CHAT}}}[{{w}}]))'
                  f' - sum(rate(homelab_http_request_duration_seconds_bucket{{{CHAT},le="15.0"}}[{{w}}]))'),
        "total": f"sum(rate(homelab_http_request_duration_seconds_count{{{CHAT}}}[{{w}}]))",
    },
    {
        "slo": "gateway-availability",
        "target": 0.995,
        "summary": "Cloudflare gateway answers without a 5xx (from the Worker's own spans)",
        "error": f'sum(rate(traces_span_metrics_calls_total{{{GATEWAY},http_response_status_code=~"5.."}}[{{w}}]))',
        "total": f"sum(rate(traces_span_metrics_calls_total{{{GATEWAY}}}[{{w}}]))",
    },
    {
        "slo": "gateway-chat-on-gpu",
        "target": 0.95,
        "summary": "Gateway chat requests answered by the GPU, not the Workers AI fallback",
        "error": (f'sum(rate(traces_span_metrics_calls_total{{{GATEWAY},http_route="/v1/chat/completions",'
                  f'http_response_status_code!~"4..",gateway_backend!="gpu"}}[{{w}}]))'),
        "total": (f'sum(rate(traces_span_metrics_calls_total{{{GATEWAY},http_route="/v1/chat/completions",'
                  f'http_response_status_code!~"4.."}}[{{w}}]))'),
    },
    {
        # Synthetic: works with zero user traffic, which is most of the time in a homelab.
        "slo": "chat-on-gpu",
        "target": 0.95,
        "summary": "The API's LLM backend is vLLM on the GPU PC, not the Ollama fallback (probed every 15 s)",
        "probe": 'probe_success{job="blackbox-llm"}',
    },
]


def ratio(slo: dict, window: str) -> str:
    if "probe" in slo:
        return f"1 - avg(avg_over_time({slo['probe']}[{window}]))"
    return f"({slo['error'].replace('{w}', window)})\n  /\n({slo['total'].replace('{w}', window)})"


def indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line for line in text.splitlines())


def render() -> str:
    out = [
        "# GENERATED by prometheus/slo/gen_slo_rules.py from its SLO table. Do not edit by hand.",
        "groups:",
    ]
    for slo in SLOS:
        name, target = slo["slo"], slo["target"]
        budget = round(1 - target, 6)
        out += [f"  - name: slo-{name}", "    rules:"]
        out += [
            "      - record: slo:objective:ratio",
            f"        expr: vector({target})",
            f"        labels: {{slo: {name}}}",
        ]
        for w in WINDOWS:
            out += [
                f"      - record: slo:sli_error:ratio_rate{w}",
                "        expr: |",
                indent(ratio(slo, w), 10),
                f"        labels: {{slo: {name}}}",
            ]
        for severity, long, short, factor in BURN_ALERTS:
            threshold = round(factor * budget, 6)
            alert = "SLOBurnRate" + ("Page" if severity == "page" else "Ticket")
            out += [
                f"      - alert: {alert}",
                "        expr: |",
                f'          slo:sli_error:ratio_rate{long}{{slo="{name}"}} > {threshold}',
                "          and",
                f'          slo:sli_error:ratio_rate{short}{{slo="{name}"}} > {threshold}',
                f"        for: {'2m' if severity == 'page' else '15m'}",
                f"        labels: {{slo: {name}, severity: {severity}, burn: \"{factor}x over {long}/{short}\"}}",
                "        annotations:",
                f'          summary: "SLO {name} ({target:.1%}): {slo["summary"]}"',
                f'          description: "Error ratio is burning the {budget:.1%} budget at {factor}x or more '
                f'over both {long} and {short}."',
            ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is out of date; run python prometheus/slo/gen_slo_rules.py")
        print("slo.yml up to date")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}")
